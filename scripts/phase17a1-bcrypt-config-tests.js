/**
 * Phase 17A.1 — Recovery Admin bcrypt config structural validation (unit only).
 * Never prints hash/secret values.
 *
 * Usage:
 *   node scripts/phase17a1-bcrypt-config-tests.js
 */
const crypto = require("crypto");
const bcrypt = require("bcryptjs");
const {
  isBcryptHash,
  verifyRecoveryAdminPassword,
} = require("./phase17a-recovery-auth-unit.cjs");

async function main() {
  const out = {};
  const mark = (id, ok, detail = "") => {
    out[id] = ok ? "PASS" : "FAIL";
    console.log(`${ok ? "PASS" : "FAIL"} ${id}${detail ? " — " + detail : ""}`);
  };

  const password = `phase17a1-${crypto.randomBytes(8).toString("hex")}`;
  const wrongPassword = `${password}-wrong`;
  const otherPassword = `other-${crypto.randomBytes(6).toString("hex")}`;
  const validHash = await bcrypt.hash(password, 4);
  const shaForPassword = crypto.createHash("sha256").update(password).digest("hex");
  const shaForOther = crypto.createHash("sha256").update(otherPassword).digest("hex");

  // A — valid full bcrypt → accepted as bcrypt
  {
    const r = await verifyRecoveryAdminPassword(password, { adminPasswordHash: validHash });
    mark("A", r.ok === true && r.mode === "bcrypt" && !r.legacy && isBcryptHash(validHash), `mode=${r.mode}`);
  }

  // B — wrong password against valid bcrypt → rejected, no SHA fallback
  {
    const r = await verifyRecoveryAdminPassword(wrongPassword, {
      adminPasswordHash: validHash,
      adminPasswordSha256: shaForPassword,
    });
    mark("B", r.ok === false && r.mode === "bcrypt" && !r.ignoredMalformedHash, `mode=${r.mode}`);
  }

  // C — "not-a-bcrypt-hash" → malformed
  {
    const fake = "not-a-bcrypt-hash";
    mark("C", isBcryptHash(fake) === false);
  }

  // D — "$2b$" → malformed
  {
    mark("D", isBcryptHash("$2b$") === false);
  }

  // E — "$2b$12$short" → malformed
  {
    mark("E", isBcryptHash("$2b$12$short") === false);
  }

  // F — full-length string with invalid bcrypt alphabet → malformed
  {
    // Keep length/prefix/cost shape; poison one body character outside ./A-Za-z0-9
    const poisoned = `${validHash.slice(0, 29)}*${validHash.slice(30)}`;
    mark(
      "F",
      poisoned.length === validHash.length &&
        poisoned.startsWith(validHash.slice(0, 7)) &&
        isBcryptHash(poisoned) === false,
      `lenMatch=${poisoned.length === validHash.length}`
    );
  }

  // G — malformed bcrypt + valid SHA → SHA fallback works
  {
    const r = await verifyRecoveryAdminPassword(password, {
      adminPasswordHash: "$2b$12$short",
      adminPasswordSha256: shaForPassword,
    });
    mark(
      "G",
      r.ok === true && r.mode === "sha256" && r.legacy === true && r.ignoredMalformedHash === true,
      `mode=${r.mode}`
    );
  }

  // H — malformed bcrypt + no legacy → configError
  {
    const r = await verifyRecoveryAdminPassword(password, {
      adminPasswordHash: "$2b$",
    });
    mark("H", r.ok === false && r.configError === true && r.ignoredMalformedHash === true, `configError=${!!r.configError}`);
  }

  // I — valid bcrypt + matching SHA for different password → SHA cannot bypass bcrypt
  {
    const r = await verifyRecoveryAdminPassword(otherPassword, {
      adminPasswordHash: validHash,
      adminPasswordSha256: shaForOther,
    });
    mark("I", r.ok === false && r.mode === "bcrypt", `mode=${r.mode}`);
  }

  // J — real bcrypt generated by bcryptjs passes validator
  {
    const generated = await bcrypt.hash(`gen-${crypto.randomBytes(4).toString("hex")}`, 6);
    mark("J", isBcryptHash(generated) === true && generated.length === 60, "bcryptjs-generated");
  }

  const fails = Object.entries(out).filter(([, v]) => v === "FAIL");
  console.log("\n========== SUMMARY ==========");
  for (const [k, v] of Object.entries(out)) console.log(`${v} ${k}`);
  console.log(fails.length ? `\nFAILED: ${fails.length}` : "\nALL PASS");
  process.exit(fails.length ? 1 : 0);
}

main().catch(() => {
  console.error("[phase17a1] test runner failed");
  process.exit(1);
});
